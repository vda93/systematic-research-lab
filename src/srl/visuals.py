"""Render one explanatory SVG directly from computed synthetic study results."""

import xml.etree.ElementTree as ET


def render_summary(result: dict) -> str:
    svg = ET.Element('svg', {'xmlns': 'http://www.w3.org/2000/svg', 'viewBox': '0 0 1240 640',
                             'role': 'img', 'aria-labelledby': 'title description'})
    ET.SubElement(svg, 'title', {'id': 'title'}).text = 'SYNTHETIC: concentration stress and a known-mean uncertainty audit'
    ET.SubElement(svg, 'desc', {'id': 'description'}).text = (
        'Left: supplied net totals and complete-cohort stress. Right: measured coverage in a fixed synthetic null experiment. '
        'Neither panel is historical trading performance.')
    ET.SubElement(svg, 'rect', {'width': '1240', 'height': '640', 'fill': '#f5f8fa'})
    group = ET.SubElement(svg, 'g', {'font-family': 'Arial, Helvetica, sans-serif', 'fill': '#132d40'})

    def label(x, y, value, size=18, color='#132d40', anchor='start', weight='400'):
        ET.SubElement(group, 'text', {'x': str(x), 'y': str(y), 'font-size': str(size),
                                     'fill': color, 'text-anchor': anchor, 'font-weight': weight}).text = str(value)

    def rect(x, y, width, height, fill, stroke='none'):
        ET.SubElement(group, 'rect', {'x': str(x), 'y': str(y), 'width': str(width), 'height': str(height),
                                     'rx': '5', 'fill': fill, 'stroke': stroke})

    def line(x1, y1, x2, y2, color='#cbd7df', dash=''):
        ET.SubElement(group, 'line', {'x1': str(x1), 'y1': str(y1), 'x2': str(x2), 'y2': str(y2),
                                     'stroke': color, 'stroke-width': '1.5', 'stroke-dasharray': dash})

    label(42, 48, 'SYNTHETIC / Stress the conclusion', 30, weight='700')
    label(42, 82, 'A constructed concentration example and a known-zero-mean calibration. No market performance.', 18, '#516b7b')
    rect(36, 115, 555, 440, '#ffffff', '#d6e1e7')
    rect(612, 115, 590, 440, '#ffffff', '#d6e1e7')
    label(62, 153, '1 / Remove complete cohorts', 22, weight='700')
    label(638, 153, '2 / Check nominal 95% interval coverage', 22, weight='700')
    main = result['main']
    count = len(main['concentration']['removed_cohorts'])
    removal = f'Remove {count} cohort' + ('' if count == 1 else 's')
    entries = [('Control', main['control']['net_total']), ('Treatment', main['treatment']['net_total']),
               (removal, main['concentration']['retained_total'])]
    scale = 122 / max(1, *(abs(value) for _, value in entries))
    base = 305
    line(78, base, 548, base, '#8ba0af')
    label(64, base + 6, '0', 14, '#516b7b')
    for index, (name, value) in enumerate(entries):
        x = 120 + index * 153
        height = abs(value) * scale
        rect(x, base - height if value >= 0 else base, 70, height, '#167d8a' if value >= 0 else '#b84e4a')
        label(x + 35, base - height - 12 if value >= 0 else base + height + 25,
              f'{value:+g}', 25, '#167d8a' if value >= 0 else '#b84e4a', 'middle', '700')
        label(x + 35, 482, name, 16, anchor='middle')
    decision = main['stop_rule']['decision']
    label(62, 522, f'Rule decision: {decision}', 20, '#b84e4a' if decision == 'REJECT' else '#167d8a', weight='700')
    calibration = result['calibration']
    rows = calibration['by_block']
    floor, extent = 432, 222
    nominal = calibration['nominal_coverage']
    target = floor - extent * nominal
    line(662, target, 1168, target, '#96561d', '5 4')
    label(662, target - 12, f'Nominal {nominal:.0%}', 15, '#96561d')
    for value in (0., .5, 1.):
        y = floor - value * extent
        if value != 1.:
            line(662, y, 1168, y)
        label(654, y + 5, f'{value:.0%}', 13, '#516b7b', 'end')
    for index, row in enumerate(rows):
        x = 700 + index * 450 / max(1, len(rows))
        height = row['coverage'] * extent
        rect(x, floor - height, 74, height, '#167d8a')
        label(x + 37, floor - height - 10, f"{row['coverage']:.1%}", 21, anchor='middle', weight='700')
        label(x + 37, 466, f"Block {row['block_size']}", 16, anchor='middle')
        label(x + 37, 493, f"SE {100*row['monte_carlo_se']:.1f} pp", 14, '#516b7b', 'middle')
    label(638, 530, f"{calibration['design']['trials']} trials per block length; every outcome retained.", 16, '#516b7b')
    label(42, 594, 'Units: synthetic net amounts (left), coverage across synthetic trials (right).', 16, '#516b7b')
    label(42, 620, 'Source: experiments/protocol.json and results/study.json; generated by srl.visuals.', 15, '#516b7b')
    ET.indent(svg, space='  ')
    return ET.tostring(svg, encoding='unicode') + '\n'
